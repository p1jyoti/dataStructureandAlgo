public class divisionOfDataType {
    public static void main(String[] args) {
        /*
            step 1 compute : 5/3 = int/int = 1
            step 2 store in the datatype containe= double 1.0
            output 1.0 not 1.67 
        */

        double x = 5/3;
        System.out.println(x);

        double x2 = 5.0/3.0;
        System.out.println(x2);

        double x3 = 5/3.0;
        System.out.println(x3);

        double x4 = 5.0/3;
        System.out.println(x4);



        


    }
}
